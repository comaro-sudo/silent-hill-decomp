#!/usr/bin/env python3
"""Generate pc_port/src/pc_door_maps.inc: every door between two maps.

Modern's door guidance (pc_doorguide.c) routes Harry to the next story goal.
Inside the loaded map it reads the map's own event list at run time. Between
maps it needs to know which map leads to which, for maps that aren't loaded:
that comes from here. Each map's mapX_sYY_events_data.c lists its events;
the ones with sysState = SysState_LoadOverlay move Harry to `mapIdx`.

Output rows: { from map, to map, required event flag, disabled event flag }.
The flags gate the door exactly as the game gates the event (events_main.c):
required must be set, disabled must be clear (a disabled flag of 867 or more
only counts for exclusive or set-flag events, which doors aren't).

Run from the repo root: python3 pc_port/tools/gen_door_graph.py [--report]
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read()


def flag_numbers():
    nums = {}
    for m in re.finditer(r"\b(EventFlag_\w+)\s*=\s*(\d+)", read(f"{ROOT}/include/event_flags.h")):
        nums[m.group(1)] = int(m.group(2))
    return nums


def main():
    report = "--report" in sys.argv
    flags = flag_numbers()
    rows = []
    for d in sorted(glob.glob(f"{ROOT}/src/maps/map*_s*")):
        name = os.path.basename(d)
        data = f"{d}/{name}_events_data.c"
        if not os.path.exists(data):
            continue
        from_idx = "MapIdx_" + name.upper()
        for e in re.finditer(r"\{([^{}]*SysState_LoadOverlay[^{}]*)\}", read(data), re.S):
            body = e.group(1)
            to = re.search(r"\.mapIdx\s*=\s*(MapIdx_\w+)", body)
            if not to:
                continue
            req = re.search(r"requiredEventFlag\s*=\s*(\w+)", body)
            dis = re.search(r"disabledEventFlag\s*=\s*(\w+)", body)
            req = req.group(1) if req else "0"
            dis = dis.group(1) if dis else "0"
            if dis != "0" and flags.get(dis, 0) >= 867:
                dis = "0"
            poi = re.search(r"pointOfInterestIdx\s*=\s*(\d+)", body)
            rows.append((from_idx, to.group(1), req, dis, int(poi.group(1)) if poi else -1))

    seen = set()
    out = []
    for r in rows:
        key = r[:4]
        if key in seen:
            continue
        seen.add(key)
        out.append(r)

    with open(f"{ROOT}/pc_port/src/pc_door_maps.inc", "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by pc_port/tools/gen_door_graph.py - do not edit.\n")
        f.write(" * { from map, to map, required event flag, disabled event flag } */\n")
        for a, b, req, dis, poi in out:
            f.write(f"{{ {a}, {b}, {req}, {dis} }}, /* point {poi} */\n")
    print(f"{len(out)} map-to-map doors")
    if report:
        for a, b, req, dis, poi in out:
            print(f"  {a[7:].lower():9s} -> {b[7:].lower():9s}  req={req}  dis={dis}")


if __name__ == "__main__":
    sys.exit(main())
